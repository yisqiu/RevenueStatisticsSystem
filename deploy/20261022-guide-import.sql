-- 仅新增中台讲解员订单同步版本表；原日报和其他业态保持。
CREATE TABLE REVENUESTATISTICSSYSTEM.GUIDE_IMPORT_STATE (
 ID VARCHAR(64) PRIMARY KEY,
 INTEGRATION_ID VARCHAR(64) NOT NULL REFERENCES REVENUESTATISTICSSYSTEM.INTEGRATIONS(ID),
 SOURCE_ID VARCHAR(100) NOT NULL,
 SOURCE_UPDATED_AT VARCHAR(26) NOT NULL,
 PAYLOAD_HASH VARCHAR(64) NOT NULL,
 IMPORTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(INTEGRATION_ID,SOURCE_ID)
);
