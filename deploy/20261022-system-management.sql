-- 增量迁移；仅用于核实过的 SZGCTRIP / REVENUESTATISTICSSYSTEM。
-- 保留原六表与全部业务记录，原程序仍可使用。
CREATE TABLE REVENUESTATISTICSSYSTEM.SYSTEM_ROLES (
 CODE VARCHAR(50) PRIMARY KEY, NAME VARCHAR(200) NOT NULL,
 DESCRIPTION VARCHAR(1200) NOT NULL, PERMISSIONS VARCHAR(2000) NOT NULL,
 ENABLED INT DEFAULT 1 NOT NULL, BUILT_IN INT DEFAULT 0 NOT NULL,
 VERSION BIGINT DEFAULT 1 NOT NULL, UPDATED_AT VARCHAR(19) NOT NULL
);
CREATE TABLE REVENUESTATISTICSSYSTEM.SYSTEM_USERS (
 SUBJECT VARCHAR(200) PRIMARY KEY, ENABLED INT DEFAULT 1 NOT NULL,
 VERSION BIGINT DEFAULT 1 NOT NULL, PHONE VARCHAR(100), SYNCED_AT VARCHAR(19),
 FOREIGN KEY (SUBJECT) REFERENCES REVENUESTATISTICSSYSTEM.IDENTITIES(SUBJECT)
);
CREATE TABLE REVENUESTATISTICSSYSTEM.SYSTEM_USER_ROLES (
 SUBJECT VARCHAR(200) NOT NULL, ROLE_CODE VARCHAR(50) NOT NULL,
 PRIMARY KEY(SUBJECT,ROLE_CODE),
 FOREIGN KEY(SUBJECT) REFERENCES REVENUESTATISTICSSYSTEM.IDENTITIES(SUBJECT),
 FOREIGN KEY(ROLE_CODE) REFERENCES REVENUESTATISTICSSYSTEM.SYSTEM_ROLES(CODE)
);
CREATE TABLE REVENUESTATISTICSSYSTEM.SYSTEM_LOGS (
 ID VARCHAR(64) PRIMARY KEY, MODULE VARCHAR(160) NOT NULL,
 ACTION VARCHAR(240) NOT NULL, RECORD_ID VARCHAR(200) NOT NULL,
 ACTOR VARCHAR(400) NOT NULL, DETAIL VARCHAR(8000) NOT NULL,
 CREATED_AT VARCHAR(19) NOT NULL
);
CREATE INDEX REVENUESTATISTICSSYSTEM.IDX_SYSTEM_LOG_TIME ON REVENUESTATISTICSSYSTEM.SYSTEM_LOGS(CREATED_AT,ID);
CREATE INDEX REVENUESTATISTICSSYSTEM.IDX_SYSTEM_ROLE_USERS ON REVENUESTATISTICSSYSTEM.SYSTEM_USER_ROLES(ROLE_CODE);
ALTER TABLE REVENUESTATISTICSSYSTEM.AUDIT_LOG ADD MODULE VARCHAR(160);
ALTER TABLE REVENUESTATISTICSSYSTEM.AUDIT_LOG ADD DETAIL VARCHAR(4000);
